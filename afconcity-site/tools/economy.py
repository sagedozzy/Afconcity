"""Economy after the AFCON ticket: businesses that earn while you are away, owned vehicles (fuel, repairs, towing, insurance), the startup salary."""
import sys, time
from harness import *
R = []
def check(n, ok, info=''):
    R.append(bool(ok)); print(('PASS ' if ok else 'FAIL ') + n + ('  ' + str(info) if info else ''), flush=True)
s = Session().load(); s.ev("() => { window.__noRender = true; }")
G = lambda e: s.run(e)
def until(expr, secs=10):
    t0 = time.time()
    while time.time() - t0 < secs:
        try:
            if G(expr): return True
        except Exception: pass
        time.sleep(0.2)
    return False
s.play(); G("talk('amina'), closeMenu(), 1")
b0 = "BIZ[0]"
G(f"P.x = {b0}.x, P.z = {b0}.z + 1.5, player.position.set(P.x, 0.04, P.z), 1"); time.sleep(0.4)
check('businesses stay closed before the match', not G("bizInteraction()"))
G("state.ticket = true, state.done = true, state.cash = 50000000, state.bank = 0, 1"); time.sleep(0.4)
check('buy prompt with the real price', 'TSh 1,200,000' in (G("(() => { const i = findInteraction(); return i && i.text; })()") or ''), G("(() => { const i = findInteraction(); return i && i.text; })()"))
G("findInteraction().act(), 1")
check('bought: paid and recorded', G("!!bizState().madafu && state.cash === 48800000"), G("state.cash"))
G("ECON.off += 2 * 3600000, 1")
check('two hours away earns TSh 50,000', G("bizStash(BIZ[0])") == 50000, G("bizStash(BIZ[0])"))
G("ECON.off += 20 * 3600000, 1")
check('earnings stop at the 8-hour cap', G("bizStash(BIZ[0])") == 200000, G("bizStash(BIZ[0])"))
c0 = G("state.cash"); G("findInteraction().act(), 1")
check('collecting pays it out', G("state.cash") - c0 == 200000 and G("bizStash(BIZ[0])") == 0)
G("ECON.off -= 30 * 3600000, 1")
check('moving the clock back earns nothing', G("bizStash(BIZ[0])") == 0)
G("ECON.off = 0, bizState().madafu.at = realNow(), 1")
# vehicles
G("buyVehicle(DEALER[0]), 1")
check('buying a boda: paid TSh 2,950,000 and parked at the garage', G("garage().length === 1 && ownedVehs.length === 1 && state.cash === 48800000 + 200000 - 2950000"), G("state.cash"))
check('a GPS waypoint to the garage', G("RT.wp && RT.wp.label === GARAGE.name"))
G("(() => { const v = ownedVehs[0]; P.x = v.x + 1, P.z = v.z, player.position.set(P.x, 0.04, P.z); return 1; })()"); time.sleep(0.3)
check('ride prompt says it is yours', 'your' in (G("(() => { const i = findInteraction(); return i && i.text; })()") or '').lower())
G("findInteraction().act(), 1"); time.sleep(0.3)
check('riding it costs nothing', G("playerVeh && playerVeh.owned") and G("state.cash") == 48800000 + 200000 - 2950000)
G("playerVeh.vf = 12, playerVeh.vx = 12 * Math.sin(playerVeh.yaw), playerVeh.vz = 12 * Math.cos(playerVeh.yaw), 1")
f0 = G("playerVeh.g.fuel"); G("(() => { for (let i = 0; i < 300; i++) { playerVeh.vf = 12; updateEconomy(0.1); } return 1; })()")
check('driving burns petrol by distance (360 m on a boda: about 0.0094 L)', abs((f0 - G("playerVeh.g.fuel")) - 360 * 2.6 / 100000) < 0.001, round(f0 - G("playerVeh.g.fuel"), 4))
check('fuel shows on the speedo', ' L' in G("(updateHUD(0.016, 1), ui.vehName.textContent)"), G("ui.vehName.textContent"))
G("playerVeh.g.fuel = 0, playerVeh.vx = 15, playerVeh.vz = 0, updateEconomy(0.016), 1")
check('an empty tank only crawls', G("Math.hypot(playerVeh.vx, playerVeh.vz) <= 2.21"))
G("playerVeh.vf = 0, playerVeh.vx = 0, playerVeh.vz = 0, exitVehicle(true), 1")
G("(() => { const v = ownedVehs[0]; v.x = GARAGE.x + 2; v.z = GARAGE.z + 6; v.m.position.set(v.x, 0.04, v.z); v.hp = 70; P.x = GARAGE.x, P.z = GARAGE.z + 2, player.position.set(P.x, 0.04, P.z); return 1; })()"); time.sleep(0.3)
check('garage prompt', 'Fuel' in (G("(() => { const i = findInteraction(); return i && i.text; })()") or ''), G("(() => { const i = findInteraction(); return i && i.text; })()"))
G("findInteraction().act(), 1")
items = G("menuItems.map(i => i.label + ' ' + i.price)")
check('garage offers a fill-up at TSh 3,050 a litre and a repair (TSh 3,000 per damage point on a boda)', any('Fill up' in i and '36600' in i for i in items) and any('Repair' in i and '90000' in i for i in items), items)
c0 = G("money()"); G("pickMenu(menuItems.findIndex(i => /Fill up/.test(i.label))), 1")
check('fill-up charged and tank full', c0 - G("money()") == 36600 and G("ownedVehs[0].g.fuel") == 12, c0 - G("money()"))
G("closeMenu(), 1")
G("(() => { const v = ownedVehs[0]; enterVehicle(v); damageVehicle(v, 200); return 1; })()"); time.sleep(0.3)
check('a wreck is towed to the garage with a tow fee', G("ownedVehs[0].g.towed === 1 && !playerVeh && !ownedVehs[0].m.visible"))
G("P.x = GARAGE.x, P.z = GARAGE.z + 2, player.position.set(P.x, 0.04, P.z), openGarage(), 1")
check('rebuild option for the towed boda', G("menuItems.some(i => /Rebuild/.test(i.label) && i.price === 300000)"), G("menuItems.map(i => i.label + ' ' + i.price)"))
c0r = G("money()"); G("pickMenu(menuItems.findIndex(i => /Rebuild/.test(i.label))), closeMenu(), 1")
check('rebuilt and back on the forecourt, charged once', G("!ownedVehs[0].g.towed && ownedVehs[0].m.visible && ownedVehs[0].hp === 100") and c0r - G("money()") == 300000, c0r - G("money()"))
G("state.insWk = Math.floor(clockDay() / 7) - 1, 1"); c0 = G("money()"); G("insuranceWeek(), 1")
check('weekly insurance charged', c0 - G("money()") == 6000, c0 - G("money()"))
# startup salary
G("foundStartup(10000000, 2), 1"); b0v = G("state.bank || 0")
G("state.clock = (clockDay() + 1) * 1440 + 8 * 60, startupDay(), 1")
check('the startup pays a founder salary each game day', G("state.bank") - b0v == 50000 and G("state.startup.cash < 10000000"), (G("state.bank") - b0v, G("state.startup.cash")))
check('runway is shown in days', G("runwayDays()") > 30, G("runwayDays()"))
G("openPhone('biz'), 1")
check('Biashara app lists the company and businesses', until("/Daladala AI/.test(document.querySelector('#phScreen').textContent) && /Madafu stand/.test(document.querySelector('#phScreen').textContent)"))
G("closePhone(), openPhone('garage'), 1")
check('Magari app lists your boda and the dealer', until("/Fuel 12.0/.test(document.querySelector('#phScreen').textContent) && /Bajaji/.test(document.querySelector('#phScreen').textContent)"))
G("closePhone(), 1")
G("writeSave(), 1")
saved = G("JSON.parse(localStorage.getItem(SAVE_KEY)).garage.length")
check('owned vehicles are saved', saved == 1)
G("newGame(), resyncOwned(), 1")
check('a new game has no vehicles', G("ownedVehs.length === 0 && !rentals.some(v => v.owned)"))
check('no page errors', not s.errors, s.errors[:4])
s.close()
print('%d/%d passed' % (sum(R), len(R)))
