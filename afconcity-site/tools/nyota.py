"""Nyota premium stars on afconcity.com (against the in-browser Supabase stand-in): the balance comes from the server,
a Bachs top-up (18+ only), crediting when the payment lands, spending on items and what each item does, and no shop for under-18 players."""
import sys, time, json
from harness import *
R = []
def check(n, ok, info=''):
    R.append(bool(ok)); print(('PASS ' if ok else 'FAIL ') + n + ('  ' + str(info) if info else ''), flush=True)
s = Session(claude=open(ROOT + '/tools/sbmock.js').read()).load(); s.ev("() => { window.__noRender = true; }")
A = s.page
GA = lambda e: A.evaluate('(s) => window.__G.run(s)', e)
DB = lambda: json.loads(A.evaluate("() => localStorage.getItem('sbmock.db') || '{}'"))
def until(G, expr, secs=12):
    t0 = time.time()
    while time.time() - t0 < secs:
        try:
            if G(expr): return True
        except Exception: pass
        time.sleep(0.25)
    return False
s.play()
GA("talk('amina'), closeMenu(), 1")
check('signed in on the website backend', until(GA, "MP.web === true && !!WEB.uid"))
check('balance comes from the server: 0 Nyota', until(GA, "NY.loaded && NY.bal === 0 && NY.items.length === 6 && NY.packs.length === 4"))
check('Nyota app on the phone', GA("APPS.some(a => a.id === 'nyota')"))
GA("openPhone('nyota'), 1")
check('the app shows the balance and the shop', until(GA, "/★ 0/.test(document.querySelector('#phScreen .ny-bal').textContent) && document.querySelectorAll('#phScreen .ph-row').length === 6"))
GA("nyBuy(NY.items.find(i => i.id === 'tag_gold')), 1"); time.sleep(0.4)
check('cannot buy with too few Nyota', GA("NY.bal === 0 && !nyHas('tag_gold')"))
check('nothing on the phone can add Nyota (state has no balance field)', GA("state.nyota === undefined && !JSON.stringify(state).includes('nyota')"))
# top-up
GA("window.__nyGo = (u) => { window.__went = u; }, phoneGo('nyota', 'packs'), 1")
check('the top-up screen lists the packs with shilling prices', until(GA, "document.querySelectorAll('#phScreen .ny-pack').length === 4 && /TSh 10,000/.test(document.querySelector('#phScreen .ny-pack.on').textContent)"))
A.evaluate("""() => { const f = document.querySelector('#phScreen .ny-form'); f.name.value = 'Zuri Hassan'; f.email.value = 'zuri@example.com'; f.requestSubmit(); }""")
check('the 18+ box must be ticked', until(GA, "!document.querySelector('#phScreen .ph-note.err').hidden && !window.__went"), GA("document.querySelector('#phScreen .ph-note.err').textContent"))
A.evaluate("""() => { const f = document.querySelector('#phScreen .ny-form'); f.adult.checked = true; f.requestSubmit(); }""")
check('goes to the Bachs payment page', until(GA, "/pay\\.bachs\\.test\\/checkout\\//.test(window.__went || '')"), GA("window.__went"))
tid = GA("lsGet('afc-topup')")
check('the top-up is remembered for the return trip', len(tid or '') == 36, tid)
check('the game was backed up to the cloud first', until(GA, "JSON.parse(localStorage.getItem('sbmock.db')).saves.length >= 1"))
check('the function was asked for the chosen pack with a signed-in token', any(l[0] == 'fn' and '"pack":"p550"' in l[2] and '"adult":true' in l[2] for l in A.evaluate("() => window.__sbmock.log")))
# coming back from Bachs
A.evaluate("(id) => history.replaceState(null, '', location.pathname + '?topup=' + id + '&utm_source=x')", tid)
GA("nyReturnFromUrl(), 1")
check('the return address is tidied (topup removed, other params kept)', GA("!/topup=/.test(location.search) && /utm_source=x/.test(location.search)"), A.evaluate("() => location.search"))
GA("closePhone(), nyWatchTopup(), 1"); time.sleep(1)
check('still pending: no Nyota yet', GA("NY.bal === 0 && NY.wait === lsGet('afc-topup')"))
A.evaluate("(id) => window.__sbmock.pay(id)", tid)
check('payment lands: 550 Nyota, with a splash', until(GA, "NY.bal === 550 && !NY.wait && !lsGet('afc-topup')", 10), GA("NY.bal"))
A.evaluate("(id) => window.__sbmock.pay(id)", tid)
GA("nyLoad(), 1"); time.sleep(0.4)
check('a repeated payment message credits nothing more', GA("NY.bal === 550"))
A.evaluate("() => history.replaceState(null, '', location.pathname + '?topup=x&cancelled=1')")
GA("nyReturnFromUrl(), openPhone('nyota'), 1")
check('a cancelled payment says nothing was charged', until(GA, "/Nothing was charged/.test(document.querySelector('#phScreen').textContent)"))
GA("closePhone(), 1")
# second player to see the golden name and fireworks
B = s.ctx.new_page(); B.on('pageerror', lambda e: s.errors.append('B: ' + str(e))); s._routes(B)
B.goto(s.url, timeout=300000); B.wait_for_function("() => { const b = document.querySelector('#btnPlay'); return b && !b.disabled; }", timeout=300000)
B.evaluate("() => { window.__noRender = true; }")
GB = lambda e: B.evaluate('(s) => window.__G.run(s)', e)
B.evaluate("() => document.querySelector('#btnPlay').click()")
B.wait_for_function("() => window.__G && window.__G.mode === 'play'", timeout=60000)
GB("talk('amina'), closeMenu(), 1")
check('the other player sees us', until(GB, "[...remotes.values()].some(r => !r.isMe || r.isMe)", 15))
# items
GA("nyBuy(NY.items.find(i => i.id === 'tag_gold')), 1")
check('golden name tag: 400 Nyota spent', until(GA, "NY.bal === 150 && nyHas('tag_gold') && nyGold()"))
check('other players see the name in gold', until(GB, "[...remotes.values()].some(r => r.tag.nm.classList.contains('gold'))", 12))
GA("NY.tagOn = false, nyEffects(), 1")
check('the golden name can be turned off', until(GB, "![...remotes.values()].some(r => r.tag.nm.classList.contains('gold'))", 12))
GA("NY.tagOn = true, nyEffects(), 1")
GA("state.done = true, bizState().madafu = { at: realNow() - 2 * 3600000 }, nyBuy(NY.items.find(i => i.id === 'pass_collect')), 1")
check('business pass for 7 days', until(GA, "NY.bal === 0 && nyHas('pass_collect') && NY.owned.pass_collect > Date.now() + 6.9 * 864e5"))
c0 = GA("money()"); GA("openPhone('biz'), 1")
check('Biashara shows Collect all', until(GA, "[...document.querySelectorAll('#phScreen button')].some(b => /Collect all/.test(b.textContent))"))
A.evaluate("() => [...document.querySelectorAll('#phScreen button')].find(b => /Collect all/.test(b.textContent)).click()")
check('collecting from the phone pays two hours of the madafu stand', abs(GA("money()") - c0 - 50000) < 400, GA("money()") - c0)
GA("closePhone(), 1")
# more Nyota for paint and fireworks
A.evaluate("() => { const d = JSON.parse(localStorage.getItem('sbmock.db')); d.wallets.find(w => w.uid === window.__G.run('WEB.uid')).nyota = 600; localStorage.setItem('sbmock.db', JSON.stringify(d)); }")
GA("nyLoad(), 1"); until(GA, "NY.bal === 600")
GA("state.cash += 5000000, buyVehicle(DEALER[0]), 1")
GA("nyBuy(NY.items.find(i => i.id === 'paint_gold')), 1")
check('gold paint bought', until(GA, "nyHas('paint_gold') && NY.bal === 300"))
GA("openPhone('garage'), 1")
check('Magari offers the paint for the boda', until(GA, "[...document.querySelectorAll('#phScreen button')].some(b => b.textContent === 'Gold paint')"))
A.evaluate("() => [...document.querySelectorAll('#phScreen button')].find(b => b.textContent === 'Gold paint').click()")
check('the boda is gold, and stays gold in the save', GA("ownedVehs[0].g.col === 0xd4a52a && ownedVehs[0].col === 0xd4a52a && JSON.parse(localStorage.getItem(SAVE_KEY)).garage[0].col === 0xd4a52a"))
GA("closePhone(), nyBuy(NY.items.find(i => i.id === 'fx_fireworks')), 1")
check('fireworks bought', until(GA, "nyHas('fx_fireworks') && NY.bal === 50"))
GA("nyFireworks(), 1")
check('fireworks go up over the player', until(GA, "Array.from(FW.life).some(l => l > 0)", 3))
check('the other player sees them too', until(GB, "Array.from(FW.life).some(l => l > 0)", 12))
GA("nyFireworks(), 1")
check('once a minute', GA("NY.fxCool - Date.now() > 50000") and 'Wait' in GA("ui.help.textContent"))
GA("nyBuy(NY.items.find(i => i.id === 'tag_gold')), 1"); time.sleep(0.4)
check('a lasting item cannot be bought twice', GA("NY.bal === 50"))
# Kiswahili
GA("applyLang('sw'), openPhone('nyota'), 1")
check('Kiswahili shop', until(GA, "/Nyota zako/.test(document.querySelector('#phScreen').textContent) && /Rangi ya dhahabu/.test(document.querySelector('#phScreen').textContent)"))
GA("closePhone(), applyLang('en'), 1")
# under 18
GA("localStorage.setItem(ABOUT_KEY, JSON.stringify({ a: { age: 'Under 18' } })), nyEffects(), openPhone('nyota'), 1")
check('under 18: no shop, no packs', until(GA, "/18 and over/.test(document.querySelector('#phScreen').textContent) && !document.querySelector('#phScreen .ny-bal')"))
GA("phoneGo('nyota', 'packs'), 1")
check('under 18: the top-up form never shows', GA("!document.querySelector('#phScreen .ny-form')"))
check('under 18: no golden name', GA("!nyGold()"))
GA("closePhone(), 1")
A.evaluate("() => { const d = JSON.parse(localStorage.getItem('sbmock.db')); d.docs.push({ coll: 'stats', id: window.__G.run('WEB.uid'), data: { about: { age: 'Under 18' } } }); localStorage.setItem('sbmock.db', JSON.stringify(d)); }")
check('under 18: the server refuses a top-up too', GA("nyFn('topup', { pack: 'p100', email: 'a@b.co', name: 'A', adult: true }).then(() => false, e => /18/.test(e.message))"))
check('no page errors', not s.errors, s.errors[:4])
s.close()
print('%d/%d passed' % (sum(R), len(R)))
